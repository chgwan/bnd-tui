export function describeCode(code) {
  if (code in BROWSER_MSG) return `${BROWSER_MSG[code]}(code ${code})`;
  if (code in ERROR_MSG) return `${ERROR_MSG[code]}(code ${code})`;
  return `内核错误码 ${code}(未知,可更新 errors.js 中的对照表)`;
}
